// Bundles workspace/ (contracts, L0-L3 references, examples) into worker/generated/workspace.ts,
// so the Worker reads exactly the same markdown as the local CLI. Run before every deploy.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = new URL('../workspace/', import.meta.url).pathname
const files = {}
const walk = dir => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name), rel = relative(root, p)
    if (statSync(p).isDirectory()) {
      if (/(^|\/)(output|scripts|manual)$/.test(rel)) continue // run outputs and code are not reference text
      walk(p)
    } else if (/\.(md|json|txt)$/.test(name)) files[rel] = readFileSync(p, 'utf8')
  }
}
walk(root)
mkdirSync(new URL('../worker/generated/', import.meta.url), { recursive: true })
writeFileSync(new URL('../worker/generated/workspace.ts', import.meta.url),
  `// Generated by scripts/bundle-workspace.mjs. Do not edit; edit workspace/ and re-run.\nexport const FILES: Record<string, string> = ${JSON.stringify(files, null, 1)}\n`)
console.log(`bundled ${Object.keys(files).length} workspace files`)
